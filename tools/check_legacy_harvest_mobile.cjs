"use strict";
const { chromium }=require("C:/Users/Keisuke/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");
const assert=require("node:assert/strict");
const path=require("node:path"),os=require("node:os");
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:"C:/Program Files/Google/Chrome/Application/chrome.exe"});
 try { for(const width of [360,390]) {
  const context=await browser.newContext({viewport:{width,height:844},isMobile:true,hasTouch:true});
  const page=await context.newPage(),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.route("https://**/*",r=>r.abort());
  await page.goto("http://127.0.0.1:4182/index.html",{waitUntil:"networkidle"});
  const f=await page.evaluate(()=>{
   const R=window.RiceOS,date=R.utils.today();
   const a=R.state.addField("QA old harvest"),b=R.state.addField("QA partial harvest");
   const group=R.state.addFieldGroup("QA harvest review");
   [a,b].forEach(id=>R.state.updateField(id,{fieldGroupId:group}));
   R.state.saveSchedule({scheduleId:"qa-old-plan",date,title:"稲刈り予定",fieldIds:[a]});
   R.state.saveFieldWork({workId:"qa-old-work",date,workName:"稲刈り",fieldIds:[a],sourceScheduleId:"qa-old-plan",memo:"Keep this",harvestReview:{yieldKg:123,yieldBasis:"玄米（乾燥調製後）"}});
   R.state.saveSchedule({scheduleId:"qa-partial-plan",date,title:"稲刈り予定",fieldIds:[b]});
   R.state.saveFieldWork({workId:"qa-partial-work",date,workName:"稲刈り",fieldIds:[b],harvestStatusByField:{[b]:"partial"}});
   R.app.show("annual");
   return {a,b,group,date,year:date.slice(0,4)};
  });
  const stored=()=>page.evaluate(()=>localStorage.getItem("rice_os_v8_stable"));
  await page.locator("#annualYear").selectOption(f.year);
  await page.evaluate(a=>window.RiceOS.screens.annual.openField(a,"work"),f.a);
  const before=await stored();
  page.once("dialog",d=>d.dismiss());
  await page.locator('[data-annual-harvest-confirm="qa-old-work"]').click();
  assert.equal(await stored(),before);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth),false);
  await page.locator('[data-annual-harvest-confirm="qa-old-work"]').locator("xpath=ancestor::div[contains(@class,'annual-compare-check')]").screenshot({path:path.join(os.tmpdir(),`legacy-harvest-confirm-${width}.png`)});
  page.once("dialog",d=>d.accept());
  await page.locator('[data-annual-harvest-confirm="qa-old-work"]').click();
  assert.equal(await page.evaluate(({a,year})=>window.RiceOS.state.harvestStatusForField(a,year).status,f),"complete");
  assert.equal(await page.evaluate(()=>window.RiceOS.state.data().fieldWorks.find(w=>w.workId==="qa-old-work").memo),"Keep this");
  await page.locator('.nav-item[data-screen="home"]:visible').click();
  await page.locator("[data-home-group-filter]").selectOption(f.group);
  assert.match(await page.locator(".home-harvest-count").innerText(),/1\/2/);
  assert.equal(await page.locator('[data-home-harvest-completed]').evaluate(el=>el.open),false);
  await page.locator('.nav-item[data-screen="calendar"]:visible').click();
  await page.locator("#calendarDisplayMode").selectOption("all");
  await page.evaluate(date=>window.RiceOS.screens.calendar.focusDate(date),f.date);
  assert.equal(await page.locator('[data-calendar-action="complete"][data-id="qa-old-plan"]').count(),0);
  assert.equal(await page.locator('[data-calendar-action="edit"][data-id="qa-old-plan"]').count(),0);
  assert.equal(await page.locator('[data-calendar-action="complete"][data-id="qa-partial-plan"]').count(),1);
  assert.match(await page.locator("#selectedDateEntries").innerText(),/稲刈り/);
  await page.screenshot({path:path.join(os.tmpdir(),`legacy-harvest-${width}.png`),fullPage:true});
  await page.evaluate(()=>window.RiceOS.state.deleteFieldWork("qa-old-work"));
  assert.equal(await page.locator('[data-calendar-action="complete"][data-id="qa-old-plan"]').count(),1);
  assert.equal(await page.evaluate(()=>window.RiceOS.state.data().schedules.some(s=>s.scheduleId==="qa-old-plan")),true);
  await page.reload({waitUntil:"networkidle"});
  assert.equal(await page.evaluate(({a,year})=>window.RiceOS.state.harvestStatusForField(a,year).status,f),"none");
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth),false);
  assert.deepEqual(errors,[]);
  console.log(`PASS legacy harvest ${width}px cancel/confirm/preserve/home fold/hidden completed plan/partial retained/delete restores/reload`);
  await context.close();
 }} finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
