"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "../assets/js/screens/annual.js"), "utf8");
const renderer = source.match(/  function renderArchiveEntry\(row\) \{[\s\S]*?\n  \}/);
assert(renderer, "Archive renderer must exist");
const fields = new Map([["a", { name: "北田" }], ["b", { name: "南田" }], ["same", { name: "北田" }], ["unnamed", { name: "" }]]);
const escape = value => String(value).replace(/[&<>"']/g, char => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char]));
const context = vm.createContext({ U: { attr: escape, escapeHTML: escape, fd: value => value }, state: { field: id => fields.get(id) }, selectedFieldId: "" });
const dateHelpers = ["isTimelineDate", "annualListDate"].map(name => {
  const match = source.match(new RegExp(`  function ${name}\\([^\\n]*\\) \\{[\\s\\S]*?\\n  \\}`));
  assert(match, `${name} must exist`);
  return match[0];
});
context.yearValue = () => "2026";
vm.runInContext(dateHelpers.join("\n") + "\n" + renderer[0] + "\nthis.render = renderArchiveEntry;", context);
const row = { kind: "fieldWork", id: "w1", date: "2026-11-08", title: "耕起", fieldIds: ["a", "b", "a", "same"], raw: { machine: "トラクター", groupName: "集約しない班名" } };
const before = JSON.stringify(row);
const target = html => html.match(/<small class="annual-archive-target"[^>]*>(.*?)<\/small>/)[1];
let html = context.render(row);
assert(html.includes('>11/8</time>'));
assert(context.render({ ...row, date: "2025-12-20" }).includes('>2025/12/20</time>'));
assert(context.render({ ...row, raw: { actualEndDate: "2027-01-02" } }).includes('>2026/11/8</time>'));
context.yearValue = () => "all";
assert(context.render(row).includes('>2026/11/8</time>'));
context.yearValue = () => "2026";
assert.equal(target(html), "北田、南田");
assert(html.includes('aria-label="対象: 北田、南田"'));
assert(html.includes('data-annual-material-field="a"'));
assert(html.includes('data-annual-record-open-kind="fieldWork"'));
assert(html.includes('data-annual-record-open-id="w1"'));
assert(html.includes("トラクター"));
assert(!html.includes("集約しない班名"));
assert.equal(JSON.stringify(row), before);
const smallTexts = markup => Array.from(markup.matchAll(/<small\b[^>]*>(.*?)<\/small>/g), match => match[1]);
assert.deepEqual(smallTexts(context.render({ ...row, title: "田植え", fieldIds: ["a"], raw: {}, target: "北田" })), ["北田"], "Field target must not repeat as info");
assert.deepEqual(smallTexts(context.render({ ...row, fieldIds: ["a", "b"], raw: {}, target: "北田、南田" })), ["北田、南田"], "Joined field targets must not repeat as info");
assert.deepEqual(smallTexts(context.render({ ...row, fieldIds: ["a", "b"], raw: {}, target: "北田・南田" })), ["北田、南田"], "Legacy fieldLabel formatting must not repeat as info");
assert.deepEqual(smallTexts(context.render({ ...row, kind: "other", fieldIds: [], raw: { targetScope: "offField" }, target: "圃場外" })), ["圃場外"], "Off-field target must appear once");
assert.deepEqual(smallTexts(context.render({ ...row, fieldIds: ["a"], raw: { material: "配合肥料" }, target: "北田" })), ["北田", "配合肥料"], "Material info must remain visible");
assert.deepEqual(smallTexts(context.render({ ...row, fieldIds: ["a"], raw: { machine: "トラクター" }, target: "北田" })), ["北田", "トラクター"], "Machine info must remain visible");
assert.deepEqual(smallTexts(context.render({ ...row, kind: "milling", fieldIds: [], raw: {}, target: "品種集計" })), ["対象未確認", "品種集計"], "Fieldless aggregate info must remain visible");
fields.get("a").name = "改名後の北田";
assert.equal(target(context.render(row)), "改名後の北田、南田、北田");
assert.equal(target(context.render({ ...row, fieldIds: ["a", "deleted", "deleted", "unnamed"] })), "改名後の北田、対象未確認");
assert.equal(target(context.render({ ...row, fieldIds: [] })), "対象未確認");
assert.equal(target(context.render({ ...row, fieldIds: ["deleted"] })), "対象未確認");
assert.equal(target(context.render({ ...row, fieldIds: [], raw: { targetScope: "offField" } })), "圃場外");
assert.equal(target(context.render({ ...row, kind: "other", fieldIds: [] })), "圃場外");
assert.equal(target(context.render({ ...row, kind: "other", fieldIds: ["a"] })), "改名後の北田");
context.selectedFieldId = "a";
assert(!context.render(row).includes("data-annual-material-field="));
fields.get("a").name = '<img src=x onerror="alert(1)">';
html = context.render({ ...row, fieldIds: ["a"] });
assert(!html.includes("<img"));
assert(target(html).startsWith("&lt;img"));
fields.get("a").name = "非常に長い圃場名".repeat(30);
assert.equal(target(context.render({ ...row, fieldIds: ["a", "b"] })), fields.get("a").name + "、南田");
console.log("PASS annual archive targets: current names, deduplication, unknown IDs, off-field, escaping, full labels, navigation attributes and no mutation");
