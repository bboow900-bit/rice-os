"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync("assets/js/screens/annual.js","utf8");
const extract=(name,next)=>source.slice(source.indexOf(`  function ${name}(`),source.indexOf(`  function ${next}(`));
const c=vm.createContext({recordFocus:"important"});
vm.runInContext(extract("isRoutineRecord","renderRecordFocus")+extract("timelineWorkEntry","timelineWaterEntry"),c);
const works=[{workId:"a",workName:"草刈り",date:"2026-06-01"},{workId:"b",workName:"田植え",date:"2026-05-14"},{workId:"c",workName:"草刈り",date:"2026-07-01",reviewImportant:true},{workId:"d",workName:"独自の重要な作業",date:"2026-07-02"}];
const before=JSON.stringify(works),entries=works.map(c.timelineWorkEntry);
assert.deepEqual(Array.from(c.focusRecords(entries),r=>r.id),["b","c","d"]);
c.recordFocus="routine";assert.deepEqual(Array.from(c.focusRecords(entries),r=>r.id),["a"]);
c.recordFocus="all";assert.equal(c.focusRecords(entries).length,4);
assert.equal(c.isRoutineRecord({kind:"growth",raw:{panicleLengthMm:1}}),false);
assert.equal(c.isRoutineRecord({kind:"growth",raw:{headingObserved:true}}),false);
assert.equal(c.isRoutineRecord({kind:"growth",raw:{stageConfirmed:true,observedStage:"heading"}}),false);
assert.equal(c.isRoutineRecord({kind:"growth",raw:{}}),true);
assert.equal(c.isRoutineRecord({kind:"growth",raw:{reviewImportant:true}}),false);
assert.equal(c.isRoutineRecord({label:"間断灌水"}),false);
assert.equal(JSON.stringify(works),before);
console.log("PASS review focus: daily separation, important override, recorded milestones, custom work visibility and no writes");
