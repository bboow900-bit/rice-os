"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const memory = new Map(), downloads = [];
let failKey = "";
const c = vm.createContext({ console, Blob, navigator: {}, document: { getElementById: () => null, querySelectorAll: () => [] },
  localStorage: { getItem: key => memory.get(key) ?? null, setItem(key, value) { if (key === failKey) throw Error("quota"); memory.set(key, value); }, removeItem: key => memory.delete(key) } });
c.window = c;
for (const name of ["utils", "schema", "storage"]) vm.runInContext(fs.readFileSync(path.join(__dirname, "../assets/js/core", `${name}.js`), "utf8"), c);
const R = c.RiceOS, S = R.storage, key = `${R.schema.STORE_KEY}:year_closure_backups`;
R.utils.download = (name, raw) => downloads.push({ name, raw });
let data = S.loadData();
data.meta.customUnknown = { retained: true }; data = S.saveData(data);
const original = memory.get(R.schema.STORE_KEY), backup = S.createYearClosureBackup(2026);
assert.equal(memory.get(R.schema.STORE_KEY), original);
assert.equal(S.yearClosureBackupInfo(2026).length, 1);
assert(!Object.hasOwn(S.yearClosureBackupInfo()[0], "raw"));
assert.equal(S.createYearClosureBackup(2026).backupId, backup.backupId);
S.exportYearClosureBackup(backup.backupId);
assert.equal(downloads[0].raw, original);
assert.match(downloads[0].name, /before_close_2026/);
data.meta.afterCloseTest = true; S.saveData(data);
S.createYearClosureBackup(2026);
assert.equal(S.yearClosureBackupInfo().length, 2);
S.exportYearClosureBackup(backup.backupId); assert.equal(downloads.at(-1).raw, original);
const before = JSON.stringify([...memory]);
assert.throws(() => S.createYearClosureBackup(2201)); assert.equal(JSON.stringify([...memory]), before);
failKey = key; assert.throws(() => S.createYearClosureBackup(2027), /全データ保存に失敗/); failKey = "";
assert.equal(JSON.stringify([...memory]), before);
memory.set(key, "corrupt"); assert.throws(() => S.createYearClosureBackup(2027)); assert.equal(memory.get(key), "corrupt");
memory.delete(key); memory.set(R.schema.STORE_KEY, `${memory.get(R.schema.STORE_KEY)} `);
assert.throws(() => S.createYearClosureBackup(2027), /別の画面/); assert.equal(memory.has(key), false);
console.log("year closure backup PASS");
